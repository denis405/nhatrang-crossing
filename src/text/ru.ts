/** "1 улица", "3 улицы", "5 улиц". */
export function streetsWord(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 'улица';
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'улицы';
  return 'улиц';
}

